export type Schluessel = keyof typeof TEXTE.en;

/** Text der Knopfleiste in der Sprache der Oberflaeche (unbekannte Sprache: Englisch), Platzhalter %s. */
export function wt(sprache: string, schluessel: Schluessel, ...werte: (string | number)[]): string {
    const satz = (TEXTE as Record<string, Record<string, string>>)[sprache] || TEXTE.en;
    let n = 0;
    return (satz[schluessel] || TEXTE.en[schluessel] || schluessel).replace(/%s/g, () => String(werte[n++] ?? ''));
}

