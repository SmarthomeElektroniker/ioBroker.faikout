export type Schluessel = keyof typeof TEXTE;

/** Sprache des Admins auf eine der 11 abbilden (unbekannt = Englisch). */
export function spracheVon(roh: unknown): Sprache {
    const s = String(roh || 'en').toLowerCase();
    return (SPRACHEN as string[]).includes(s) ? (s as Sprache) : s.startsWith('zh') ? 'zh-cn' : 'en';
}

/** Text in der Sprache; %s der Reihe nach ersetzt. */
export function t(sprache: string, schluessel: Schluessel, ...werte: (string | number)[]): string {
    const eintrag: Eintrag = TEXTE[schluessel];
    let n = 0;
    return (eintrag[spracheVon(sprache)] || eintrag.en).replace(/%s/g, () => String(werte[n++] ?? ''));
}
