let aktuell = 'de';

/**
 * Setzt die Sprache aller Regeltexte. Unbekannte Sprache -> Englisch.
 *
 * @param {unknown} code  Sprachkuerzel (system.config common.language)
 * @returns {string} die nun geltende Sprache
 */
function setzeSprache(code) {
    const c = String(code || '')
        .trim()
        .toLowerCase();
    aktuell = SPRACHEN.includes(c) ? c : 'en';
    return aktuell;
}

/** @returns {string} geltende Sprache */
function sprache() {
    return aktuell;
}

/**
 * Text zu einem Schluessel in der geltenden Sprache; Platzhalter `{name}` werden aus `werte`
 * gefuellt (auch undefined/null - wie in einer Zeichenkettenvorlage). Ein unbekannter Schluessel
 * kommt selbst zurueck, ein nicht gelieferter Platzhalter bleibt stehen.
 *
 * @param {string} schluessel  Schluessel der Tabelle
 * @param {Record<string, unknown>} [werte]  Werte der Platzhalter
 * @returns {string} Text
 */
function t(schluessel, werte) {
    const eintrag = Object.prototype.hasOwnProperty.call(TEXTE, schluessel) ? TEXTE[schluessel] : null;
    if (!eintrag) {
        return schluessel;
    }
    const roh = eintrag[aktuell] || eintrag.en || eintrag.de;
    if (!werte) {
        return roh;
    }
    return roh.replace(/\{(\w+)\}/g, (ganz, name) =>
        Object.prototype.hasOwnProperty.call(werte, name) ? zahlText(werte[name]) : ganz,
    );
}

/** Sprachen mit Punkt als Dezimalzeichen; alle anderen der elf schreiben ein Komma. */
const PUNKT_SPRACHEN = new Set(['en', 'zh-cn']);

/**
 * Wert eines Platzhalters als Text. Zahlen (auch als Zeichenkette aus toFixed) bekommen das
 * Dezimalzeichen der geltenden Sprache und ein echtes Minuszeichen: de "−2,3", en "-2.3".
 * Alles andere (Namen, IDs, Uhrzeiten, zusammengesetzte Texte) bleibt unveraendert.
 *
 * @param {unknown} wert  Wert des Platzhalters
 * @returns {string} Text
 */
function zahlText(wert) {
    const text = String(wert);
    if (PUNKT_SPRACHEN.has(aktuell) || !(typeof wert === 'number' || /^[+-]?\d+\.\d+$/.test(text))) {
        return text;
    }
    return text.replace('.', ',').replace(/^-/, '−');
}

module.exports = { t, zahlText, setzeSprache, sprache, TEXTE, SPRACHEN };
